// Extracts whitelisted Phosphor SVG paths into a compact TypeScript glyph map.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const WHITELIST_PATH = path.join(ROOT, "src", "ui", "icons", "icons.json");
const OUTPUT_PATH = path.join(ROOT, "src", "ui", "icons", "glyphs.generated.ts");
const ASSETS_DIR = path.join(ROOT, "node_modules", "@phosphor-icons", "core", "assets");

const WEIGHTS = ["regular", "light", "fill"];

function extractPaths(svgContent) {
  const matches = svgContent.matchAll(/<path\s+[^>]*d="([^"]+)"[^>]*>/g);
  const paths = [];
  for (const match of matches) {
    paths.push(match[1]);
  }
  if (paths.length === 0) {
    throw new Error("No path found in SVG content");
  }
  return paths;
}

function build() {
  const whitelist = JSON.parse(fs.readFileSync(WHITELIST_PATH, "utf8"));
  whitelist.sort();

  const glyphs = {};

  for (const name of whitelist) {
    glyphs[name] = {};
    for (const weight of WEIGHTS) {
      const filename = weight === "regular" ? `${name}.svg` : `${name}-${weight}.svg`;
      const filePath = path.join(ASSETS_DIR, weight, filename);

      if (!fs.existsSync(filePath)) {
        throw new Error(`Phosphor icon "${name}" not found at ${filePath}`);
      }

      const content = fs.readFileSync(filePath, "utf8");
      glyphs[name][weight] = extractPaths(content);
    }
  }

  const nameUnion = whitelist.map((n) => `  | "${n}"`).join("\r\n");

  const tsContent = [
    "// Auto-generated by scripts/build-icons.cjs from @phosphor-icons/core. Do not edit.",
    "",
    "export type IconName =",
    nameUnion + ";",
    "",
    'export type IconWeight = "regular" | "light" | "fill";',
    "",
    "export const GLYPHS: Record<IconName, Record<IconWeight, readonly string[]>> = " +
      JSON.stringify(glyphs, null, 2).replace(/\n/g, "\r\n") +
      " as const;",
    "",
  ].join("\r\n");

  fs.writeFileSync(OUTPUT_PATH, tsContent, "utf8");
  console.log(`Successfully generated ${whitelist.length} icons in ${OUTPUT_PATH}`);
}

build();
