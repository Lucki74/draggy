/** How many each language is expected to carry, so none quietly falls behind. */
export const GREETING_COUNT = 159;

const FALLBACK = "en";

/** The greetings for a language, falling back to English for anything else. */
export function greetingsFor(language: string): string[] {
  const pool = GREETINGS[language];
  return pool && pool.length > 0 ? pool : GREETINGS[FALLBACK];
}

/** Spreads similar seeds across the set. Chat ids differ by only a character or two, so taking the
 * first of them would land on the same greeting every time. */
// A new salt each launch, so a chat keeps its line within a run but the lines move between runs.
const SALT = Math.random().toString(36).slice(2);

function scatter(seed: string): number {
  const text = SALT + seed;
  let value = 5381;
  for (let index = 0; index < text.length; index++) {
    value = Math.imul(value ^ text.charCodeAt(index), 0x5bd1e995);
  }
  // Murmur's finalizer spreads near-identical seeds across the whole range.
  value ^= value >>> 16;
  value = Math.imul(value, 0x85ebca6b);
  value ^= value >>> 13;
  value = Math.imul(value, 0xc2b2ae35);
  value ^= value >>> 16;
  return value >>> 0;
}

/** The greeting for one chat. The same chat always gets the same line, so it does not change under
 * the reader; a different chat gets a different one. */
export function pickGreeting(language: string, seed: string): string {
  const pool = greetingsFor(language);
  return pool[scatter(seed ?? "") % pool.length];
}
