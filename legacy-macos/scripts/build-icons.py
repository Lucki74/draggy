#!/usr/bin/env python3
"""Builds legacy-macos/Draggy/Resources/Icons.xcassets and Glyph.generated.swift from the Windows glyph table.

The Windows renderer already whitelists the Phosphor glyphs it uses, so both apps draw the same set.
Run it after changing app/src/ui/icons/glyphs.generated.ts: python3 legacy-macos/scripts/build-icons.py
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "app/src/ui/icons/glyphs.generated.ts"
LOGO = ROOT / "app/src/assets/dragon.png"
CATALOG = ROOT / "legacy-macos/Draggy/Resources/Icons.xcassets"
SWIFT = ROOT / "legacy-macos/Draggy/Theme/Glyph.generated.swift"
WEIGHTS = {"regular": "", "light": "-light", "fill": "-fill"}

INFO = {"author": "xcode", "version": 1}


def parse(text):
    body = text[text.index("export const GLYPHS"):]
    glyphs = {}
    for name, block in re.findall(r'^  "([a-z0-9-]+)": \{(.*?)^  \}', body, re.S | re.M):
        weights = {}
        for weight, paths in re.findall(r'"(regular|light|fill)": \[(.*?)\]', block, re.S):
            weights[weight] = re.findall(r'"([^"]+)"', paths)
        glyphs[name] = weights
    return glyphs


def write_json(path: Path, value: object) -> None:
    path.write_bytes((json.dumps(value, indent=2) + "\n").encode("utf-8"))


def imageset(name: str, filename: str, data: bytes, vector: bool) -> None:
    folder = CATALOG / f"{name}.imageset"
    folder.mkdir(parents=True)
    (folder / filename).write_bytes(data)
    properties = {"template-rendering-intent": "template"}
    if vector:
        properties["preserves-vector-representation"] = True
    write_json(folder / "Contents.json", {
        "images": [{"filename": filename, "idiom": "universal"}],
        "info": INFO,
        "properties": properties,
    })


def case_name(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def main() -> None:
    glyphs = parse(SOURCE.read_text(encoding="utf-8"))
    if not glyphs:
        raise SystemExit(f"no glyphs found in {SOURCE}")

    if CATALOG.exists():
        shutil.rmtree(CATALOG)
    CATALOG.mkdir(parents=True)
    write_json(CATALOG / "Contents.json", {"info": INFO})

    for name, weights in sorted(glyphs.items()):
        for weight, suffix in WEIGHTS.items():
            paths = weights.get(weight) or weights.get("regular") or []
            svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256" width="256" height="256">'
            svg += "".join(f'<path d="{d}"/>' for d in paths) + "</svg>\n"
            asset = f"ph-{name}{suffix}"
            imageset(asset, f"{asset}.svg", svg.encode("utf-8"), vector=True)

    imageset("DragonMark", "dragon.png", LOGO.read_bytes(), vector=False)

    lines = [
        "// Generated by legacy-macos/scripts/build-icons.py from app/src/ui/icons/glyphs.generated.ts. Do not edit.",
        "",
        "/// The Phosphor glyphs both apps may draw. Each has a regular, light and fill image in Icons.xcassets.",
        "enum Glyph: String, CaseIterable, Sendable {",
    ]
    lines += [f'    case {case_name(name)} = "{name}"' for name in sorted(glyphs)]
    lines += ["}", ""]
    SWIFT.parent.mkdir(parents=True, exist_ok=True)
    SWIFT.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"{len(glyphs)} glyphs written to {CATALOG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
